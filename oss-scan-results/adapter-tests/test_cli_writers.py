class RunRecordWriteProtocolTest(unittest.TestCase):
    """The run record goes through the *strong* write path, not a second one (F11).

    ``normalize-run.json`` used to be written with a pathname-based sequence of its own
    — validate the string, ``mkdir(parents=True)``, ``os.open`` the computed path,
    ``os.replace`` — while ``emit.py`` already owned a descriptor-bound publisher for the
    dataset. Every step of that sequence re-resolved the name, so a parent or a final
    component swapped between the check and the open redirected or replaced the
    publication and nothing afterwards could tell (CWE-367, CWE-59).

    What is asserted here is that there is now **one** write path and the record is on
    it: the pathname-based primitives are gone from ``emit`` altogether, the writer calls
    ``emit.publish_document``, and the flags that publisher opens with are exclusive and
    no-follow. The protocol's own behaviour — the component walk, the held directory
    descriptor, the inode binding, the fsyncs — is asserted in
    ``test_emit_publication.py``, which is where that module's contract lives; this test
    is about which path ``cli.py`` uses.
    """

    #: The primitives the weak path consisted of. They were removed with their last
    #: caller rather than left as public API nothing calls, so their continued absence
    #: is the assertion: a reintroduced ``stage_text`` is a second write path, and a
    #: second write path means two sets of guarantees with no way to tell which a given
    #: file got.
    REMOVED_PRIMITIVES = (
        "stage_text",
        "promote_staged",
        "discard_staged",
        "StagedWrite",
        "_STAGED_OPEN_FLAGS",
        "_STAGED_TOKEN_BYTES",
    )

    def test_the_open_flags_are_exclusive_create_and_no_follow(self) -> None:
        flags = emit._STAGING_OPEN_FLAGS
        for bit, name in (
            (os.O_CREAT, "O_CREAT"),
            (os.O_EXCL, "O_EXCL"),
            (os.O_WRONLY, "O_WRONLY"),
            (os.O_NOFOLLOW, "O_NOFOLLOW"),
        ):
            with self.subTest(flag=name):
                self.assertTrue(flags & bit, f"{name} is not requested")
        # O_TRUNC would mean an existing file at the staged name is a target rather than
        # an error, which is exactly what O_EXCL exists to prevent.
        self.assertFalse(flags & os.O_TRUNC)

    def test_the_pathname_based_write_primitives_are_gone(self) -> None:
        """No second write path exists to fall back onto, by name or in ``__all__``."""
        for name in self.REMOVED_PRIMITIVES:
            with self.subTest(name=name):
                self.assertFalse(
                    hasattr(emit, name),
                    f"emit.{name} is back; the run record and the dataset must share "
                    "one write path",
                )
                self.assertNotIn(name, emit.__all__)
        for name in emit.__all__:
            with self.subTest(exported=name):
                self.assertTrue(
                    hasattr(emit, name), f"emit.__all__ names {name}, which does not exist"
                )

    def test_the_writer_publishes_through_the_descriptor_bound_publisher(self) -> None:
        """Asserted against the source: which function is called is the whole finding."""
        source = inspect.getsource(cli._write_run_record)
        self.assertIn("emit.publish_document", source)
        for removed in ("emit.stage_text", "emit.promote_staged", "emit.discard_staged"):
            with self.subTest(call=removed):
                self.assertNotIn(removed, source)

    def test_the_staged_name_is_not_guessable(self) -> None:
        """Two stagings of one target produce two different temporary names.

        Taken from the namer the publisher uses, because the staged file itself never
        outlives a publication: it is renamed on success and unlinked on failure, so
        there is no moment at which a test could list it.
        """
        first = emit._temporary_name(cli.RUN_RECORD_FILENAME)
        second = emit._temporary_name(cli.RUN_RECORD_FILENAME)
        self.assertNotEqual(first, second)
        self.assertNotEqual(first, cli.RUN_RECORD_FILENAME)
        self.assertTrue(first.startswith(f".{cli.RUN_RECORD_FILENAME}."))
        self.assertTrue(first.endswith(".staged"))

    def test_a_published_run_record_leaves_no_residue_and_carries_0o644(self) -> None:
        """The observable end state of one publication, in the directory it wrote into."""
        with tempfile.TemporaryDirectory(prefix="blitzy-run-record-protocol-") as directory:
            root = Path(directory)
            target = root / cli.RUN_RECORD_FILENAME
            result = cli._write_run_record(target, {"exit_status": {"code": 0}}, owner=root)
            self.assertEqual(
                sorted(entry.name for entry in root.iterdir()),
                [cli.RUN_RECORD_FILENAME],
            )
            self.assertEqual(stat.S_IMODE(target.stat().st_mode), 0o644)
            self.assertEqual(result["mode_octal"], "0o644")
            self.assertEqual(result["role"], cli.RUN_RECORD_ROLE)
            self.assertEqual(result["bytes_written"], target.stat().st_size)
            self.assertEqual(
                result["sha256"], hashlib.sha256(target.read_bytes()).hexdigest()
            )


