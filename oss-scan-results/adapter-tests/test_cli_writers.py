class StagedWriteFlagsTest(unittest.TestCase):
    """The one write primitive every output goes through is exclusive and no-follow."""

    def test_the_open_flags_are_exclusive_create_and_no_follow(self) -> None:
        flags = emit._STAGED_OPEN_FLAGS
        for bit, name in (
            (os.O_CREAT, "O_CREAT"),
            (os.O_EXCL, "O_EXCL"),
            (os.O_WRONLY, "O_WRONLY"),
            (os.O_NOFOLLOW, "O_NOFOLLOW"),
        ):
            with self.subTest(flag=name):
                self.assertTrue(flags & bit, f"{name} is not requested")
        # O_TRUNC would mean an existing file at the staged name is a target rather than
        # an error, which is exactly what O_EXCL exists to prevent.
        self.assertFalse(flags & os.O_TRUNC)

    def test_the_staged_name_is_not_guessable(self) -> None:
        """Two stagings of one target produce two different temporary names."""
        with tempfile.TemporaryDirectory(prefix="blitzy-staged-name-") as directory:
            root = Path(directory)
            target = root / "findings.json"
            first = emit.stage_text(target, "one\n", boundary=root)
            second = emit.stage_text(target, "two\n", boundary=root)
            try:
                self.assertNotEqual(first.temporary, second.temporary)
                self.assertNotEqual(first.temporary.name, "findings.json.partial")
                self.assertTrue(first.temporary.name.startswith(".findings.json."))
                self.assertTrue(first.temporary.name.endswith(".partial"))
                self.assertFalse(target.exists())
            finally:
                emit.discard_staged([first, second])
            self.assertEqual(sorted(entry.name for entry in root.iterdir()), [])


