#: The field-name syntax the parser requires, compiled here from the pattern cli.py
#: publishes rather than restated, so the two cannot drift apart.
FIELD_NAME_RE = re.compile(rf"\A{cli._STATUS_KEY_PATTERN}\Z")

#: The absolute directory the authored ``.status`` bodies below carry as their
#: ``scan_root`` value.
#:
#: It is deliberately *not* any clone's real scan root.  The subject of every test that
#: uses it is :func:`cli._runner_status`, to which a value is opaque text: the parser
#: neither resolves it, nor stats it, nor compares it with the recorded metadata.  Naming
#: a real root here would tie a parser test to whichever tree the run that produced this
#: checkout happened to use -- the absolute literal this constant replaced was exactly
#: that, and it went stale the moment the pipeline was re-run against a different clone --
#: and would break the module in the next clone for a reason that has nothing to do with
#: parsing.  A single obviously-synthetic constant keeps the module
#: hermetic: it reads no metadata document at import time, so
#: :class:`CommittedStatusFileTest` remains the only test here that touches the committed
#: tree and remains free to skip when that tree is absent.
STATUS_SCAN_ROOT = "/status-parser-fixture-root/spark-src"

#: What a bypassed :func:`cli._validate_document_bounds` returns: a verdict nothing can
#: exceed, so the agreement check on the accepted path has no opinion to disagree with.
#: Used only by :func:`bypass_pre_parse_gate`.
_NO_OPINION: dict[str, int] = {
    "depth": sys.maxsize,
    "nodes": sys.maxsize,
    "longest_string": sys.maxsize,
    "numeric_literal_digits": 0,
}


def lift_cap(test: unittest.TestCase, module: Any, name: str, value: int) -> None:
    """Raise one cap for the duration of ``test``, restoring it afterwards.

    The mirror image of the technique the refusal tests use: they LOWER a cap so a bound can
    be crossed by a file small enough to write in a unit test, and the three tests below
    RAISE one so a document can reach the arm *past* the bound -- ``json``'s own recursion
    limit, or CPython's integer-conversion limit -- which the pre-parse gate would otherwise
    refuse first.  The restoration is an ``addCleanup`` rather than a ``finally`` because the
    assertions that follow read the patched value back (``halt.details["depth_cap"]`` is
    compared against the live constant), so the cap has to stay lifted until the test method
    has finished.

    The production values are asserted in :class:`IngestionBoundConstantsTest`, which is what
    keeps both techniques sound.
    """
    previous = getattr(module, name)
    test.addCleanup(setattr, module, name, previous)
    setattr(module, name, value)


def bypass_pre_parse_gate(test: unittest.TestCase) -> None:
    """Disable the pre-parse structural gate for the duration of ``test``.

    Two tests need it, and both have the same subject: an arm that runs AFTER a parse and
    that the gate would otherwise pre-empt.  For the runner metadata that arm is not
    hypothetical -- ``paths.load_runner_metadata`` performs its own read of the file, so a
    document swapped between the gate's read and that one still reaches its post-parse shape
    check, and that check is the only thing standing behind the gate.  For an artifact the
    arms are defence in depth against this gate being wrong.  Either way the arm has to stay
    covered, and covering it means arranging for the gate not to answer first.

    Nothing else in this module bypasses it: every other test exercises the real gate.
    """
    real = cli._validate_document_bounds
    test.addCleanup(setattr, cli, "_validate_document_bounds", real)

    def no_opinion(text: str, **caps: int) -> dict[str, int]:
        return dict(_NO_OPINION)

    cli._validate_document_bounds = no_opinion  # type: ignore[assignment]


