# F15 -- untrusted verbatim text: the residual risk cli.py measures instead of escaping
# ======================================================================================


def control_characters_in(value: Any) -> set[str]:
    """Return every character of the inventory's subject set reachable inside ``value``.

    Walks every string in a nested structure -- mapping keys included -- so the claim under
    test is the one the record makes about itself, *"the character it reports never appears
    in the inventory"*, rather than the absence of whichever single character a test
    happened to look for.  Membership is decided by :data:`cli._CONTROL_TABLE`, so the
    walk's idea of a control character and the inventory's are the same one.
    """
    found: set[str] = set()
    if isinstance(value, str):
        found.update(character for character in value if ord(character) in cli._CONTROL_TABLE)
    elif isinstance(value, dict):
        for key, nested in value.items():
            found |= control_characters_in(key)
            found |= control_characters_in(nested)
    elif isinstance(value, (list, tuple)):
        for nested in value:
            found |= control_characters_in(nested)
    return found


#: One runner stream carrying, in order, every hazard F15 names: a carriage return that
#: overwrites the line already printed, two ANSI escape introducers (erase-line and
#: set-window-title, the second with its BEL terminator), and a NUL that truncates the
#: value in a consumer reading C strings.  Authored here rather than captured, because no
#: committed stream carries such a payload -- which is the whole reason F15 is latent -- and
#: because a hand-written body is the only way to assert an exact count per code point.
HOSTILE_STREAM: str = (
    "opengrep: 1 rule loaded\r"
    "\x1b[2K"
    "\x1b]0;compromised\x07"
    "scan complete, 0 findings\x00"
    "\n"
)

#: The inventory :data:`HOSTILE_STREAM` must produce, hand-counted from the literal above:
#: one NUL, one BEL, one LF, one CR and two ESC.
HOSTILE_STREAM_COUNTS: dict[str, int] = {
    "U+0000": 1,
    "U+0007": 1,
    "U+000A": 1,
    "U+000D": 1,
    "U+001B": 2,
}


class ControlCharacterInventoryTest(unittest.TestCase):
    """The inventory is a real measurement, and it never reproduces what it reports.

    ``cli.py`` may not escape a runner's own words (AAP 0.5.4, 0.6.1, 0.6.2), so it takes
    the other route F15 allows: keep the bytes and measure the hazard beside them.  A
    disclosure nobody can check is a claim rather than a measurement, which is what these
    assertions are for -- the counts are hand-verified against the literal above, and the
    non-reproduction is asserted over every string in the inventory rather than over one.
    """

    def setUp(self) -> None:
        self._directory = tempfile.TemporaryDirectory(prefix="blitzy-control-inventory-")
        self.addCleanup(self._directory.cleanup)
        self.log_dir = Path(self._directory.name)

    def stream(self, body: str, *, name: str = "osv-scanner.stderr.log") -> Path:
        """Write ``body`` as a runner stream, in bytes, and return its path."""
        path = self.log_dir / name
        path.write_bytes(body.encode("utf-8"))
        return path

    def counts_of(self, inventory: Mapping[str, Any]) -> dict[str, int]:
        return {entry["code_point"]: entry["count"] for entry in inventory["by_code_point"]}

    # -- the measurement itself ---------------------------------------------------------

    def test_a_stream_carrying_cr_esc_and_nul_is_measured_by_code_point_and_count(self) -> None:
        record = cli._stream_record(self.stream(HOSTILE_STREAM), with_text=True)
        inventory = record["text_control_characters"]

        self.assertTrue(inventory["measured"])
        self.assertEqual(inventory["characters_measured"], len(HOSTILE_STREAM))
        self.assertEqual(self.counts_of(inventory), HOSTILE_STREAM_COUNTS)
        self.assertEqual(inventory["occurrences"], sum(HOSTILE_STREAM_COUNTS.values()))
        self.assertEqual(inventory["distinct_code_points"], len(HOSTILE_STREAM_COUNTS))
        self.assertEqual(
            [entry["abbreviation"] for entry in inventory["by_code_point"]],
            ["NUL", "BEL", "LF", "CR", "ESC"],
        )
        for entry in inventory["by_code_point"]:
            with self.subTest(code_point=entry["code_point"]):
                self.assertEqual(entry["class"], cli.CONTROL_CLASS_C0)
                self.assertTrue(entry["rendering_effect"].strip())

    def test_the_inventory_never_reproduces_the_character_it_reports(self) -> None:
        """The point of the disclosure: it describes the hazard without carrying it.

        Asserted in both directions.  Nothing in the inventory -- or in any other field of
        the entry -- holds one of these characters, and the verbatim ``text`` beside it
        holds all of them, which is what makes the first half a measurement of the second
        rather than of a value somebody already cleaned.
        """
        record = cli._stream_record(self.stream(HOSTILE_STREAM), with_text=True)
        inventory = record["text_control_characters"]

        self.assertFalse(inventory["character_reproduced"])
        self.assertEqual(control_characters_in(inventory), set())

        disclosure = {key: value for key, value in record.items() if key != "text"}
        self.assertEqual(
            control_characters_in(disclosure),
            set(),
            msg="a control character reached a field other than the verbatim text",
        )
        self.assertEqual(
            control_characters_in(record["text"]),
            {"\x00", "\x07", "\n", "\r", "\x1b"},
        )
        # Described, not reproduced: the code point appears as text and the character does
        # not. The converse -- a code point written where the character should be -- would
        # mean the verbatim excerpt had been escaped, which AAP 0.5.4 forbids.
        self.assertIn("U+001B", json.dumps(inventory))
        self.assertNotIn("U+001B", record["text"])

    def test_a_measured_text_with_no_controls_reports_zero_rather_than_nothing(self) -> None:
        """``occurrences: 0`` and ``measured: false`` are different facts, and both are said."""
        inventory = cli._control_character_inventory("opengrep: 0 findings")
        self.assertTrue(inventory["measured"])
        self.assertEqual(inventory["occurrences"], 0)
        self.assertEqual(inventory["distinct_code_points"], 0)
        self.assertEqual(inventory["by_code_point"], [])
        self.assertEqual(inventory["characters_measured"], len("opengrep: 0 findings"))
        self.assertNotIn("null_reason", inventory)

    def test_a_null_text_says_it_was_not_measured_and_why(self) -> None:
        inventory = cli._control_character_inventory(None)
        self.assertFalse(inventory["measured"])
        self.assertIsNone(inventory["characters_measured"])
        self.assertIsNone(inventory["occurrences"])
        self.assertIsNone(inventory["distinct_code_points"])
        self.assertEqual(inventory["by_code_point"], [])
        self.assertIn("nothing to measure", inventory["null_reason"])
        self.assertEqual(inventory["escaping_contract"], cli.UNTRUSTED_TEXT_CONTRACT_KEY)

    def test_both_forms_carry_the_definition_of_the_measurement(self) -> None:
        """The subject set and the method travel with the numbers, not only with the source."""
        for text in (None, "plain", HOSTILE_STREAM):
            with self.subTest(text="null" if text is None else repr(text[:12])):
                inventory = cli._control_character_inventory(text)
                self.assertEqual(inventory["subject_set"], cli._CONTROL_SUBJECT_SET)
                self.assertEqual(inventory["method"], cli._CONTROL_METHOD)
                self.assertIn("category Cc", inventory["subject_set"])
                self.assertIn("bidirectional", inventory["subject_set"])

    def test_the_inventory_is_ordered_by_code_point_and_is_reproducible(self) -> None:
        """No timestamp, no ordering by first appearance: an unchanged input, an equal record."""
        reversed_order = "\x1b" + "\x0c" + "\x00" + "\u202e" + "\x7f"
        inventory = cli._control_character_inventory(reversed_order)
        code_points = [entry["code_point"] for entry in inventory["by_code_point"]]
        self.assertEqual(code_points, sorted(code_points))
        self.assertEqual(code_points, ["U+0000", "U+000C", "U+001B", "U+007F", "U+202E"])
        self.assertEqual(
            json.dumps(inventory),
            json.dumps(cli._control_character_inventory(reversed_order)),
        )

    # -- the subject set, which decides what the measurement can see ---------------------

    def test_every_code_point_in_the_subject_set_has_a_class_and_an_abbreviation(self) -> None:
        expected = (
            list(range(0x00, 0x20))
            + [0x7F]
            + list(range(0x80, 0xA0))
            + list(cli.BIDIRECTIONAL_FORMATTING_CODE_POINTS)
        )
        self.assertEqual(sorted(cli._CONTROL_TABLE), sorted(expected))
        self.assertEqual(len(cli._CONTROL_TABLE), 32 + 1 + 32 + 12)
        classes = {
            cli.CONTROL_CLASS_C0,
            cli.CONTROL_CLASS_DELETE,
            cli.CONTROL_CLASS_C1,
            cli.CONTROL_CLASS_BIDIRECTIONAL,
        }
        for code_point in expected:
            with self.subTest(code_point=f"U+{code_point:04X}"):
                control_class, abbreviation = cli._CONTROL_TABLE[code_point]
                self.assertIn(control_class, classes)
                self.assertTrue(abbreviation)
                self.assertEqual(abbreviation, abbreviation.upper())
                self.assertTrue(abbreviation.isalnum())

    def test_every_class_has_a_stated_effect_so_the_fallback_cannot_fail(self) -> None:
        """A code point with no entry of its own still gets a sentence, not a null."""
        for control_class in (
            cli.CONTROL_CLASS_C0,
            cli.CONTROL_CLASS_DELETE,
            cli.CONTROL_CLASS_C1,
            cli.CONTROL_CLASS_BIDIRECTIONAL,
        ):
            with self.subTest(control_class=control_class):
                self.assertTrue(cli._CONTROL_CLASS_EFFECTS[control_class].strip())
        # U+0011 (DC1) has no entry of its own, so it exercises the fallback.
        self.assertNotIn(0x11, cli._CONTROL_RENDERING_EFFECTS)
        entry = cli._control_character_inventory("\x11")["by_code_point"][0]
        self.assertEqual(entry["abbreviation"], "DC1")
        self.assertEqual(
            entry["rendering_effect"], cli._CONTROL_CLASS_EFFECTS[cli.CONTROL_CLASS_C0]
        )

    def test_a_bidirectional_override_is_counted_under_its_own_class(self) -> None:
        """Invisible reordering is the other way rendered text stops matching the bytes."""
        entry = cli._control_character_inventory("a\u202eb")["by_code_point"][0]
        self.assertEqual(entry["code_point"], "U+202E")
        self.assertEqual(entry["class"], cli.CONTROL_CLASS_BIDIRECTIONAL)
        self.assertEqual(entry["abbreviation"], "RLO")
        self.assertIn("CWE-451", entry["rendering_effect"])

    def test_a_character_outside_the_subject_set_is_not_counted(self) -> None:
        """The set is closed, and its boundary is asserted rather than left to be inferred."""
        inventory = cli._control_character_inventory("a\u2003b\u200bc\ufeffd")
        self.assertEqual(inventory["occurrences"], 0)
        self.assertEqual(inventory["characters_measured"], 7)

    def test_the_table_is_built_from_the_ranges_so_it_cannot_drift(self) -> None:
        """A spare abbreviation is a fault in the table and fails when the module loads."""
        source = inspect.getsource(cli._build_control_table)
        self.assertIn("_CONTROL_ABBREVIATIONS[code_point]", source)
        self.assertIn("raise AssertionError", source)
        self.assertEqual(
            sorted(set(cli._CONTROL_ABBREVIATIONS) - set(cli._CONTROL_TABLE)), []
        )


class VerbatimTextRetentionTest(unittest.TestCase):
    """The tool's own words stay byte-equal to the file (AAP 0.5.4, 0.6.1, 0.6.2).

    The measurement beside them would be worthless if producing it had changed them, and
    the disclosure would be false: the run record's contract says these fields are carried
    *"byte for byte, unescaped and unrewritten"*, and that is a claim about bytes.
    """

    def setUp(self) -> None:
        self._directory = tempfile.TemporaryDirectory(prefix="blitzy-verbatim-text-")
        self.addCleanup(self._directory.cleanup)
        self.log_dir = Path(self._directory.name)

    def stream(self, body: bytes, *, name: str = "osv-scanner.stderr.log") -> Path:
        path = self.log_dir / name
        path.write_bytes(body)
        return path

    def test_the_embedded_words_are_byte_equal_to_the_file_they_came_from(self) -> None:
        path = self.stream(HOSTILE_STREAM.encode("utf-8"))
        record = cli._stream_record(path, with_text=True)

        self.assertEqual(record["text"].encode("utf-8"), path.read_bytes())
        self.assertFalse(record["text_truncated"])
        # The measurements beside it are over the whole file, as they were before.
        self.assertEqual(record["bytes"], len(path.read_bytes()))
        self.assertEqual(
            record["sha256"], hashlib.sha256(path.read_bytes()).hexdigest()
        )

    def test_not_one_hazard_was_neutralised_on_the_way_in(self) -> None:
        record = cli._stream_record(
            self.stream(HOSTILE_STREAM.encode("utf-8")), with_text=True
        )
        for hazard, name in (
            ("\r", "CR"),
            ("\x1b", "ESC"),
            ("\x00", "NUL"),
            ("\x07", "BEL"),
        ):
            with self.subTest(hazard=name):
                self.assertIn(hazard, record["text"])

    def test_a_carriage_return_survives_the_read_so_it_can_be_measured(self) -> None:
        """Universal-newline mode would have destroyed the primary CWE-117 hazard.

        Measured rather than supposed: with ``newline=None`` -- Python's default -- a stream
        written as ``b"first\\rsecond\\r\\nthird\\n"`` came back as
        ``"first\\nsecond\\nthird\\n"``, so the excerpt was not the tool's bytes and no CR
        could ever appear in the inventory, however hostile the stream.  The reader passes
        ``newline=""`` for exactly that reason, and this asserts the consequence rather than
        the keyword alone.
        """
        path = self.stream(b"first\rsecond\r\nthird\n")
        record = cli._stream_record(path, with_text=True)

        self.assertEqual(record["text"], "first\rsecond\r\nthird\n")
        counts = {
            entry["code_point"]: entry["count"]
            for entry in record["text_control_characters"]["by_code_point"]
        }
        self.assertEqual(counts, {"U+000A": 2, "U+000D": 2})
        self.assertIn('newline=""', inspect.getsource(cli._read_bounded_text))

    def test_the_bound_still_applies_and_still_says_when_it_cut(self) -> None:
        """The disclosure is added beside the cap, not in place of it (CWE-400)."""
        body = ("\x1b" * 4) + ("n" * (cli.TOOL_WORDS_EXCERPT_LIMIT + 500))
        path = self.stream(body.encode("utf-8"))
        record = cli._stream_record(path, with_text=True)

        self.assertTrue(record["text_truncated"])
        self.assertEqual(len(record["text"]), cli.TOOL_WORDS_EXCERPT_LIMIT)
        # The inventory describes the EXCERPT the record carries, which is the text a
        # consumer will render; the file's own size and digest are still whole-file.
        self.assertEqual(
            record["text_control_characters"]["characters_measured"],
            cli.TOOL_WORDS_EXCERPT_LIMIT,
        )
        self.assertEqual(
            record["text_control_characters"]["by_code_point"][0]["count"], 4
        )
        self.assertEqual(record["bytes"], len(body.encode("utf-8")))


class VerbatimDisclosureShapeTest(unittest.TestCase):
    """Every entry that embeds untrusted text carries the same two disclosure keys.

    A consumer that has to test for the inventory's presence will forget to, so the shape
    is uniform on every path out of :func:`cli._stream_record`, :func:`cli._tool_words` and
    :func:`cli._runner_status` -- present file, absent file, no log tree at all, and a
    status file refused for its size.
    """

    def setUp(self) -> None:
        self._directory = tempfile.TemporaryDirectory(prefix="blitzy-disclosure-shape-")
        self.addCleanup(self._directory.cleanup)
        self.log_dir = Path(self._directory.name)

    def assert_disclosed(self, entry: Mapping[str, Any], *, where: str) -> None:
        """Assert one entry carries the inventory and the contract pointer."""
        with self.subTest(entry=where):
            self.assertEqual(
                entry["text_escaping_contract"], cli.UNTRUSTED_TEXT_CONTRACT_KEY
            )
            inventory = entry["text_control_characters"]
            self.assertIn("measured", inventory)
            self.assertFalse(inventory["character_reproduced"])
            self.assertEqual(inventory["subject_set"], cli._CONTROL_SUBJECT_SET)

    def test_every_stream_entry_carries_the_disclosure_whether_or_not_it_embeds_text(self) -> None:
        present = self.log_dir / "gitleaks.stdout.log"
        present.write_bytes(b"one line\n")
        absent = self.log_dir / "gitleaks.stderr.log"
        for with_text in (False, True):
            self.assert_disclosed(
                cli._stream_record(present, with_text=with_text),
                where=f"present/with_text={with_text}",
            )
            self.assert_disclosed(
                cli._stream_record(absent, with_text=with_text),
                where=f"absent/with_text={with_text}",
            )

    def test_a_tool_with_no_log_directory_still_carries_the_disclosure(self) -> None:
        words = cli._tool_words(None, "osv-scanner", with_text=True)
        for stream in ("stderr", "stdout"):
            self.assert_disclosed(words["streams"][stream], where=f"no-log-dir/{stream}")
        self.assertFalse(words["stated_reason_control_characters"]["measured"])
        self.assertIn(
            "no stream carried words",
            words["stated_reason_control_characters_source"],
        )
        self.assertEqual(
            words["stated_reason_escaping_contract"], cli.UNTRUSTED_TEXT_CONTRACT_KEY
        )

    def test_the_stated_reason_inventory_is_its_stream_projected_not_measured_again(self) -> None:
        """One measurement cited twice, the discipline the run record applies elsewhere."""
        (self.log_dir / "osv-scanner.stderr.log").write_bytes(
            b"No package sources found, --help for usage information.\x1b[0m\n"
        )
        words = cli._tool_words(self.log_dir, "osv-scanner", with_text=True)

        self.assertEqual(words["stated_reason_stream"], "stderr")
        self.assertEqual(
            words["stated_reason_control_characters_source"],
            "streams.stderr.text_control_characters",
        )
        self.assertIs(
            words["stated_reason_control_characters"],
            words["streams"]["stderr"]["text_control_characters"],
        )
        counts = {
            entry["code_point"]: entry["count"]
            for entry in words["stated_reason_control_characters"]["by_code_point"]
        }
        self.assertEqual(counts, {"U+000A": 1, "U+001B": 1})
        # The words themselves are unchanged, which is what _classify_no_work reads.
        self.assertIn("No package sources found", words["stated_reason"])

    def test_a_status_record_carries_the_disclosure_on_every_path(self) -> None:
        self.assert_disclosed(
            cli._runner_status(None, "trivy"), where="no-log-dir"
        )
        self.assert_disclosed(
            cli._runner_status(self.log_dir, "trivy"), where="absent-file"
        )
        (self.log_dir / "trivy.status").write_bytes(b"tool=trivy\nexit_code=0\n")
        self.assert_disclosed(
            cli._runner_status(self.log_dir, "trivy"), where="parsed"
        )
        previous = cli.STATUS_FILE_BYTE_LIMIT
        cli.STATUS_FILE_BYTE_LIMIT = 4
        try:
            refused = cli._runner_status(self.log_dir, "trivy")
        finally:
            cli.STATUS_FILE_BYTE_LIMIT = previous
        self.assertEqual(
            [entry["class"] for entry in refused["defects"]],
            [cli.STATUS_DEFECT_FILE_TOO_LARGE],
        )
