class RunnerMetadataShapeBoundTest(_OutputTargetTestCase):
    """The metadata is bounded on SHAPE, by the module that owns its read.

    ``cli._load_metadata`` can only bound what it can see before the call: the file's size.
    Depth, node count and string length are properties of the parsed document, which only
    ``paths.load_runner_metadata`` ever holds -- so the bound belongs there, and a caller
    that reaches that function directly (a test, a later consumer) gets it too rather than
    the unbounded read that used to be there (CWE-400, CWE-674, CWE-770).

    Each test asserts the refusal's *reason*: the structured ``stage`` the raising module
    attached and the cap it names, and that ``cli`` forwards both into the fault it records
    in ``normalize-run.json``.  A refusal a record cannot attribute to a step is a refusal
    nobody can act on.
    """

    def _patch(self, name: str, value: int) -> None:
        """Lower one cap for the duration of a test, restoring it afterwards.

        The caps are far above real data by design -- 200,000 nodes against the committed
        1,315 -- so a document that crosses one honestly would be megabytes of fixture.
        Lowering the cap tests the same branch against the same code, which is the
        convention :class:`RunnerMetadataBoundTest` already uses for the byte cap.
        """
        previous = getattr(paths, name)
        setattr(paths, name, value)
        self.addCleanup(setattr, paths, name, previous)

    def test_a_document_nested_past_the_depth_cap_is_refused_on_shape(self) -> None:
        depth = paths.METADATA_DEPTH_LIMIT + 8
        self.runner_metadata.write_text("[" * depth + "]" * depth, encoding="utf-8")
        with self.assertRaises(paths.RunnerMetadataError) as caught:
            paths.load_runner_metadata(self.runner_metadata)
        error = caught.exception
        self.assertEqual(error.details["stage"], "shape")
        self.assertEqual(error.details["depth_cap"], paths.METADATA_DEPTH_LIMIT)
        self.assertIn("nests to at least", str(error))

    def test_a_document_holding_more_values_than_the_node_cap_is_refused(self) -> None:
        self._patch("METADATA_NODE_LIMIT", 16)
        self.runner_metadata.write_text(
            json.dumps({"tools": {str(index): index for index in range(64)}}),
            encoding="utf-8",
        )
        with self.assertRaises(paths.RunnerMetadataError) as caught:
            paths.load_runner_metadata(self.runner_metadata)
        self.assertEqual(caught.exception.details["stage"], "shape")
        self.assertEqual(caught.exception.details["node_cap"], 16)
        self.assertIn("more than 16 JSON values", str(caught.exception))

    def test_a_string_value_past_the_string_cap_is_refused(self) -> None:
        self._patch("METADATA_STRING_LIMIT", 32)
        self.runner_metadata.write_text(
            json.dumps({"tools": {"opengrep": {"path_base": "b" * 64}}}),
            encoding="utf-8",
        )
        with self.assertRaises(paths.RunnerMetadataError) as caught:
            paths.load_runner_metadata(self.runner_metadata)
        self.assertEqual(caught.exception.details["stage"], "shape")
        self.assertIn("carries a string of 64 characters", str(caught.exception))

    def test_a_member_NAME_past_the_string_cap_is_refused_too(self) -> None:
        """A member name is not a value, and an implementation checking only values misses it."""
        self._patch("METADATA_STRING_LIMIT", 32)
        self.runner_metadata.write_text(
            json.dumps({"n" * 64: "short"}), encoding="utf-8"
        )
        with self.assertRaises(paths.RunnerMetadataError) as caught:
            paths.load_runner_metadata(self.runner_metadata)
        self.assertIn("member name of 64 characters", str(caught.exception))

    def test_the_size_cap_is_enforced_inside_the_read_as_well(self) -> None:
        """A direct caller gets the byte cap too, not only the caller that stats first."""
        self._patch("METADATA_BYTE_LIMIT", 32)
        self.runner_metadata.write_text(
            json.dumps({"tools": {"opengrep": {"path_base": "b" * 64}}}),
            encoding="utf-8",
        )
        with self.assertRaises(paths.RunnerMetadataError) as caught:
            paths.load_runner_metadata(self.runner_metadata)
        self.assertEqual(caught.exception.details["stage"], "size")
        self.assertEqual(caught.exception.details["byte_cap"], 32)
        self.assertIn("refused before any of it was read", str(caught.exception))

    def test_a_document_that_is_not_utf8_is_refused_at_the_decode(self) -> None:
        self.runner_metadata.write_bytes(b'{"tools": {"opengrep": "\xff\xfe"}}')
        with self.assertRaises(paths.RunnerMetadataError) as caught:
            paths.load_runner_metadata(self.runner_metadata)
        self.assertEqual(caught.exception.details["stage"], "decode")

    def test_cli_forwards_the_structured_detail_into_the_fault_it_records(self) -> None:
        """``paths``'s own post-parse shape refusal is still forwarded with its stage.

        ``cli`` now refuses this document on the text before ``paths`` is called at all, so
        the gate is bypassed here to reach the arm this test is about.  That arm is not dead
        code: ``paths.load_runner_metadata`` performs its own read, so a document swapped
        between the gate's read and that one reaches its post-parse shape check, and this
        assertion is what proves the refusal is still attributable to the step that made it.
        """
        bypass_pre_parse_gate(self)
        depth = paths.METADATA_DEPTH_LIMIT + 8
        self.runner_metadata.write_text("[" * depth + "]" * depth, encoding="utf-8")
        inputs = self.resolve()
        with self.assertRaises(cli.ConfigurationFault) as caught:
            cli._load_metadata(inputs, {})
        fault = caught.exception
