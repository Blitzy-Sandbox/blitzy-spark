class MetadataSingleReadTest(unittest.TestCase):
    """The metadata gate validates and the parse consumes ONE set of bytes (F12, CWE-367).

    The pre-parse gate lives in :mod:`normalize.cli` while the parse lives in
    :func:`normalize.paths.load_runner_metadata`.  While that function read the file
    itself, the composed path read it twice, and a replacement landing between the two
    reads reached ``json.loads`` with none of the structural caps applied to it.  The
    ``validated_text`` parameter closes that window, and these tests hold it closed.
    """

    def _document(self, tools: object = None) -> str:
        return json.dumps({"tools": tools if tools is not None else {"opengrep": {}}})

    def test_validated_text_is_parsed_and_the_file_is_not_reread(self) -> None:
        """The bytes handed over are the bytes parsed, whatever is on disk."""
        with tempfile.TemporaryDirectory() as directory:
            location = Path(directory) / "runner-metadata.json"
            # On disk: a document naming one tool.  Handed over: a different one.
            location.write_text(self._document({"on_disk": {}}), encoding="utf-8")
            handed = self._document({"handed_over": {}})
            document = paths.load_runner_metadata(location, validated_text=handed)
            self.assertIn("handed_over", document["tools"])
            self.assertNotIn(
                "on_disk",
                document["tools"],
                msg="the file was re-read, so the parse and the gate saw different bytes",
            )

    def test_validated_text_still_gets_the_shape_check_after_the_parse(self) -> None:
        """The second opinion is not skipped by the shorter route."""
        with tempfile.TemporaryDirectory() as directory:
            location = Path(directory) / "runner-metadata.json"
            location.write_text(self._document(), encoding="utf-8")
            deep = "[" * (paths.METADATA_DEPTH_LIMIT + 4)
            deep += "]" * (paths.METADATA_DEPTH_LIMIT + 4)
            with self.assertRaises(paths.RunnerMetadataError) as caught:
                paths.load_runner_metadata(
                    location, validated_text='{"tools": ' + deep + "}"
                )
            self.assertIn("shape", str(caught.exception.details.get("stage", "")))

    def test_validated_text_over_the_byte_cap_is_refused_before_the_parse(self) -> None:
        """The cap applies to handed-over text too, and says where it came from."""
        with tempfile.TemporaryDirectory() as directory:
            location = Path(directory) / "runner-metadata.json"
            location.write_text(self._document(), encoding="utf-8")
            oversized = '{"tools": {"x": "' + "a" * (paths.METADATA_BYTE_LIMIT + 8) + '"}}'
            with self.assertRaises(paths.RunnerMetadataError) as caught:
                paths.load_runner_metadata(location, validated_text=oversized)
            details = caught.exception.details
            self.assertEqual(details.get("stage"), "size")
            self.assertEqual(details.get("source"), "validated_text")

    def test_omitting_validated_text_still_reads_and_bounds_the_file(self) -> None:
        """The standalone route is unchanged, so a direct caller loses nothing."""
        with tempfile.TemporaryDirectory() as directory:
            location = Path(directory) / "runner-metadata.json"
            location.write_text(self._document({"from_disk": {}}), encoding="utf-8")
            document = paths.load_runner_metadata(location)
            self.assertIn("from_disk", document["tools"])
            location.write_text("{not json", encoding="utf-8")
            with self.assertRaises(paths.RunnerMetadataError) as caught:
                paths.load_runner_metadata(location)
            self.assertEqual(caught.exception.details.get("stage"), "parse")

    def test_cli_hands_the_validated_text_to_the_parse(self) -> None:
        """White-box: the composed path passes the text rather than the path alone."""
        source = inspect.getsource(cli._load_metadata)
        self.assertIn("validated_text=text", source)
        self.assertNotIn(
            "del text",
            source,
            msg="the text must survive to be handed to the parse",
        )
        signature = inspect.signature(paths.load_runner_metadata)
        parameter = signature.parameters["validated_text"]
        self.assertEqual(parameter.kind, inspect.Parameter.KEYWORD_ONLY)
