class DirectMetadataLoadPreParseGateTest(unittest.TestCase):
    """The EXPORTED metadata loader bounds the document itself, on every route (F12).

    THE DEFECT THIS CLASS EXISTS FOR
    --------------------------------
    ``paths.load_runner_metadata`` is in ``paths.__all__``, so ``cli`` is not its only
    caller: a test, an adapter test, or a later consumer can reach it directly.  Called
    without ``validated_text`` it used to bounded-read and go straight to ``json.loads``,
    applying the depth, node and string caps only to the object graph that parse had
    already allocated -- the same post-mortem-instead-of-a-bound defect the artifact route
    had (CWE-400, CWE-674, CWE-770).  And the ``validated_text`` route trusted the caller's
    label instead of measuring the text it was handed.

    Every test here therefore asserts the ORDER as well as the verdict, and asserts it on
    BOTH routes: the refusal is the ``shape`` verdict this module has always raised, with
    the cap it crossed, and ``json.loads`` was never reached for the input that produced it.
    The instrumentation is the technique :class:`PreParseStructuralGateTest` uses -- a
    recording ``json.loads`` -- which covers ``paths``' parser too, because that module
    parses through the same ``json`` module attribute.
    """

    def setUp(self) -> None:
        directory = tempfile.TemporaryDirectory(prefix="blitzy-metadata-gate-")
        self.addCleanup(directory.cleanup)
        self.location = Path(directory.name) / cli.RUNNER_METADATA_FILENAME

    # -- instrumentation ------------------------------------------------------------

    def record_the_parses(self) -> list[int]:
        """Record the length of every ``json.loads`` argument for this test's duration.

        The recording delegates to the real parser rather than raising, so a gate that
        failed to refuse produces the downstream failure the assertions then name instead
        of an artificial one.  Every document here is small enough for that delegation to
        be safe if it ever happens.
        """
        calls: list[int] = []
        real_loads = json.loads

        def recording(text: Any, *args: Any, **kwargs: Any) -> Any:
            calls.append(len(text) if isinstance(text, str) else -1)
            return real_loads(text, *args, **kwargs)

        self.addCleanup(setattr, json, "loads", real_loads)
        json.loads = recording  # type: ignore[assignment]
        return calls

    @contextlib.contextmanager
    def cap(self, name: str, value: int) -> Any:
        """Lower one published cap for one case, restoring it on the way out.

        The caps are far above real data by design -- 200,000 nodes against the committed
        1,315 -- so a document that crossed one honestly would be megabytes of fixture.
        Lowering the cap exercises the same branch of the same code, which is the
        convention :class:`RunnerMetadataShapeBoundTest` and the byte-cap tests already use.
        """
        previous = getattr(paths, name)
        setattr(paths, name, value)
        try:
            yield
        finally:
            setattr(paths, name, previous)

    def hostile_cases(
        self,
    ) -> tuple[tuple[str, str, str, int, int, tuple[str, int] | None], ...]:
        """One case per bound the gate can raise: name, body, bound, cap, observed, patch.

        Six cases for six bounds, which is ``paths.DOCUMENT_BOUNDS`` exactly --
        :meth:`test_every_bound_the_gate_can_raise_has_a_case_here` holds that true, so a
        bound added to the gate cannot arrive with no pre-parse coverage on this route.
        """
        deep = paths.METADATA_DEPTH_LIMIT + 8
        return (
            (
                "over-deep",
                "[" * deep + "]" * deep,
                paths.DOCUMENT_BOUND_DEPTH,
                paths.METADATA_DEPTH_LIMIT,
                paths.METADATA_DEPTH_LIMIT + 1,
                None,
            ),
            (
                "over-node",
                json.dumps({"tools": {str(index): index for index in range(64)}}),
                paths.DOCUMENT_BOUND_NODES,
                16,
                17,
                ("METADATA_NODE_LIMIT", 16),
            ),
            (
                "over-string",
                json.dumps({"tools": {"opengrep": {"path_base": "b" * 64}}}),
                paths.DOCUMENT_BOUND_STRING,
                32,
                64,
                ("METADATA_STRING_LIMIT", 32),
            ),
            (
                "over-long member name",
                json.dumps({"n" * 64: "short"}),
                paths.DOCUMENT_BOUND_MEMBER_NAME,
                32,
                64,
                ("METADATA_STRING_LIMIT", 32),
            ),
            (
                "over-digit",
                '{"tools": {"opengrep": {"n": ' + "9" * 5_000 + "}}}",
                paths.DOCUMENT_BOUND_NUMERIC_DIGITS,
                paths.STATUS_NUMERIC_DIGIT_LIMIT,
                5_000,
                None,
            ),
            (
                "over-long bare word",
                '{"tools": ' + "z" * 200 + "}",
                paths.DOCUMENT_BOUND_LITERAL_TOKEN,
                paths.STATUS_NUMERIC_DIGIT_LIMIT,
                200,
                None,
            ),
        )

    def assert_refused_on_shape(
        self,
        error: paths.RunnerMetadataError,
        bound: str,
        limit: int,
        observed: int,
    ) -> None:
        """Assert the refusal is the pre-existing ``shape`` verdict, naming its measurement."""
        self.assertEqual(error.details["stage"], "shape")
        self.assertEqual(error.details["bound"], bound)
        self.assertEqual(error.details["bound_cap"], limit)
