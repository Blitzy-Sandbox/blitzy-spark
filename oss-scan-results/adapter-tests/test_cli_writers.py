class RunRecordPersistenceTest(unittest.TestCase):
    """The record is staged, read back, parsed and only then published -- or it is a failure.

    Four guarantees, unchanged by F11's move onto ``emit.publish_document`` and asserted
    here on their consequences rather than on the calls that deliver them:

    * a record that publishes carries exactly the bytes that were serialised, and parses;
    * a record that cannot be staged raises and leaves nothing behind;
    * bytes that are not a JSON object are caught **before** anything is renamed, so they
      never become the published record;
    * a failure leaves the previously published record exactly as it was.
    """

    def setUp(self) -> None:
        self._directory = tempfile.TemporaryDirectory(prefix="blitzy-run-record-")
        self.addCleanup(self._directory.cleanup)
        self.root = Path(self._directory.name)
        self.target = self.root / cli.RUN_RECORD_FILENAME

    def listing(self) -> list[str]:
        return sorted(entry.name for entry in self.root.iterdir())

    def test_a_written_record_is_promoted_and_parses(self) -> None:
        result = cli._write_run_record(
            self.target, {"exit_status": {"code": 0}}, owner=self.root
        )
        self.assertEqual(self.listing(), [cli.RUN_RECORD_FILENAME])
        self.assertEqual(result["path"], str(self.target))
        self.assertGreater(result["bytes_written"], 0)
        self.assertIn("read back from disk", result["verified"])
        self.assertEqual(
            json.loads(self.target.read_text(encoding="utf-8")),
            {"exit_status": {"code": 0}},
        )

    def test_a_staging_failure_raises_and_leaves_nothing_behind(self) -> None:
        blocked = self.root / "blocker"
        blocked.write_text("not a directory\n", encoding="utf-8")
        with self.assertRaises(cli.RunRecordNotPersisted) as caught:
            cli._write_run_record(
                blocked / cli.RUN_RECORD_FILENAME, {"a": 1}, owner=self.root
            )
        self.assertIn(cli.RUN_RECORD_DOCUMENT, str(caught.exception))
        self.assertEqual(self.listing(), ["blocker"])

    def test_a_symlinked_record_target_raises_rather_than_following_it(self) -> None:
        real = self.root / "real.json"
        real.write_text("{}\n", encoding="utf-8")
        link = self.root / cli.RUN_RECORD_FILENAME
        link.symlink_to(real)
        with self.assertRaises(cli.RunRecordNotPersisted):
            cli._write_run_record(link, {"a": 1}, owner=self.root)
        self.assertEqual(real.read_text(encoding="utf-8"), "{}\n")

    def test_bytes_that_are_not_an_object_are_caught_before_anything_is_renamed(self) -> None:
        """Serialising is not evidence that a document is on the device.

        The renderer is replaced so the staged file holds an array rather than an object,
        which is the only way to arrange bytes that are valid JSON and are not a record.
        The writer's validator runs on the STAGED file, so the refusal must happen with
        nothing renamed: an empty directory afterwards is the assertion, because a
        published non-object would be a run record no reader can use.
        """
        real_publish = emit.publish_document

        def publish_something_else(
            path: Any,
            _render: Callable[..., Any],
            *,
            role: str,
            newline: str = "\n",
            validate: Callable[..., Any] | None = None,
        ) -> Any:
            return real_publish(
                path,
                lambda handle: handle.write("[]\n"),
                role=role,
                newline=newline,
                validate=validate,
            )

        emit.publish_document = publish_something_else  # type: ignore[assignment]
        try:
            with self.assertRaises(cli.RunRecordNotPersisted) as caught:
                cli._write_run_record(self.target, {"a": 1}, owner=self.root)
        finally:
            emit.publish_document = real_publish  # type: ignore[assignment]
        self.assertIn("rather than an object", str(caught.exception))
        self.assertEqual(self.listing(), [])

    def test_a_failure_leaves_the_previously_published_record_untouched(self) -> None:
        cli._write_run_record(self.target, {"generation": "first"}, owner=self.root)
        published = self.target.read_bytes()
        real_publish = emit.publish_document

        def refuse(*_args: Any, **_kwargs: Any) -> Any:
            raise OSError("the device refused the staged write")

        emit.publish_document = refuse  # type: ignore[assignment]
        try:
            with self.assertRaises(cli.RunRecordNotPersisted):
                cli._write_run_record(
                    self.target, {"generation": "second"}, owner=self.root
                )
        finally:
            emit.publish_document = real_publish  # type: ignore[assignment]
        self.assertEqual(self.target.read_bytes(), published)
        self.assertEqual(self.listing(), [cli.RUN_RECORD_FILENAME])

    def test_the_published_bytes_are_re_read_bound_to_the_verified_inode(self) -> None:
        """The published read is inode-bound, so a repointed name is refused not read.

        Arranged by moving the published record aside and putting a different file at
        the pathname the instant the rename completes — which is the swap a pathname
        re-read cannot detect (CWE-367). ``emit.open_verified_member`` is handed the
        identity the publication measured, so it refuses the impostor and the run
        record's own persistence fails loudly.
        """
        real_replace = emit._OutputDirectory.replace

        def replace_then_swap(directory: Any, source_name: str, target_name: str) -> None:
            real_replace(directory, source_name, target_name)
            published = directory.path / target_name
            published.rename(directory.path / "moved-aside.json")
            (directory.path / target_name).write_text('{"impostor": true}\n', encoding="utf-8")

        emit._OutputDirectory.replace = replace_then_swap  # type: ignore[assignment]
        try:
            with self.assertRaises(cli.RunRecordNotPersisted) as caught:
                cli._write_run_record(self.target, {"generation": "real"}, owner=self.root)
        finally:
            emit._OutputDirectory.replace = real_replace  # type: ignore[assignment]
        message = str(caught.exception)
        self.assertIn("not the", message)
        self.assertIn("inode", message)
        self.assertEqual(
            json.loads(self.target.read_text(encoding="utf-8")), {"impostor": True}
        )

    def test_the_record_is_written_on_a_halt_as_well_as_on_success(self) -> None:
        """A halt's own account of itself is the one thing that must always land."""
        halt = cli._halt(cli.HALT_RECONCILIATION, "a halting condition in the data")
        record = {"exit_status": {"code": cli.EXIT_HALT, "outcome": "halted"}}
        record["halt"] = halt.as_dict()
        cli._write_run_record(self.target, record, owner=self.root)
        published = json.loads(self.target.read_text(encoding="utf-8"))
        self.assertEqual(published["halt"]["reason"], cli.HALT_RECONCILIATION)
        self.assertEqual(published["exit_status"]["code"], cli.EXIT_HALT)


class MainOutcomeTest(_OutputTargetTestCase):
    """A run whose record was lost never reports success (CWE-703).

    ``main`` reads ``os.environ`` itself and is the only place the promotion from a
    successful exit code to the record's own failure happens, so these two tests drive it
    directly.  The pipeline is stubbed -- its correctness is every other module's subject --
    and the guard under test is the real one.
    """

    def run_main(
        self,
        *,
        argv: Sequence[str] = (),
        environment: Mapping[str, str] | None = None,
        execute: Callable[..., None] | None = None,
        publish_document: Callable[..., Any] | None = None,
        working_directory: Path | None = None,
    ) -> tuple[int, str, str]:
        """Run ``cli.main`` with a captured environment, cwd and console.

        ``publish_document`` replaces the publisher the run record is written through,
        which is how the lost-record outcome below is arranged. It stands where a
        ``stage_text`` hook used to: the writer moved onto the descriptor-bound
        publisher (F11) and the guarantee under test — a lost record sinks the run — is
        unchanged.
        """
        saved_environ = dict(os.environ)
        saved_execute = cli._execute
        saved_publish = emit.publish_document
        saved_cwd = os.getcwd()
        out, err = io.StringIO(), io.StringIO()
        try:
            os.environ.clear()
            os.environ.update(self.env if environment is None else environment)
            if execute is not None:
                cli._execute = execute  # type: ignore[assignment]
            if publish_document is not None:
                emit.publish_document = publish_document  # type: ignore[assignment]
            if working_directory is not None:
                os.chdir(working_directory)
            with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
                code = cli.main(list(argv))
        finally:
            os.chdir(saved_cwd)
            cli._execute = saved_execute  # type: ignore[assignment]
            emit.publish_document = saved_publish  # type: ignore[assignment]
            os.environ.clear()
            os.environ.update(saved_environ)
        return code, out.getvalue(), err.getvalue()

    @staticmethod
    def _stub_execute(_inputs: cli.Inputs, record: dict[str, Any]) -> None:
        """Stand in for the pipeline: fill the totals the success line quotes."""
        record["totals"] = {"rows": 3, "artifacts_present": 1, "artifacts_absent": 8}

    def test_a_completed_run_reports_the_record_it_verified(self) -> None:
        code, out, err = self.run_main(execute=self._stub_execute)
        self.assertEqual(code, cli.EXIT_OK)
        self.assertIn("wrote 3 row(s)", out)
        self.assertIn("read back and parsed before it was promoted", out)
        self.assertEqual(err, "")
        record = json.loads(
            (self.log_dir / cli.RUN_RECORD_FILENAME).read_text(encoding="utf-8")
        )
        self.assertEqual(record["exit_status"], {"code": 0, "outcome": "completed"})
        self.assertIn("output_guards", record["inputs"])

    def test_a_lost_run_record_turns_a_completed_run_into_a_failure(self) -> None:
        def refuse(*_args: Any, **_kwargs: Any) -> Any:
            raise OSError("the log tree refused the staged write")

        code, out, err = self.run_main(
            execute=self._stub_execute, publish_document=refuse
        )
        self.assertNotEqual(code, cli.EXIT_OK)
        self.assertEqual(code, cli.EXIT_CONFIG)
        # No success line anywhere, on either stream.
        self.assertNotIn("wrote 3 row(s)", out)
        self.assertNotIn("run record written to", out + err)
        self.assertIn("could not be written and verified", err)
        self.assertIn("required evidence", err)
        self.assertIn("NO run record was persisted", err)
        self.assertFalse((self.log_dir / cli.RUN_RECORD_FILENAME).exists())
        # And nothing was staged and abandoned in the log tree.
        self.assertEqual(
            sorted(entry.name for entry in self.log_dir.iterdir()),
            [cli.RUNNER_METADATA_FILENAME],
        )

    def test_with_no_log_tree_nothing_is_written_and_the_run_says_why(self) -> None:
        """The removed fallback, observed: no record lands in the working directory."""
        started_in = self.tmp / "started-here"
        started_in.mkdir()
        code, out, err = self.run_main(
            environment={"SPARK_SRC": str(self.spark_src)},
            working_directory=started_in,
        )
        self.assertEqual(code, cli.EXIT_CONFIG)
        self.assertEqual(sorted(entry.name for entry in started_in.iterdir()), [])
        self.assertIn("no working-directory fallback", err)
        self.assertIn("no run record was written", err)
        self.assertEqual(out, "")


