class RunnerStatusParserTest(unittest.TestCase):
    """Assert :func:`cli._runner_status` line by line, on files written for the purpose.

    The parser's contract is narrow on purpose and every clause of it is a defence against
    one observed shape of composed status file.  Each test below names the clause it
    exercises and the shadowing it prevents.
    """

    def setUp(self) -> None:
        self._directory = tempfile.TemporaryDirectory(prefix="blitzy-status-parser-")
        self.addCleanup(self._directory.cleanup)
        self.log_dir = Path(self._directory.name)

    def parse(self, text: str, *, tool: str = "trivy") -> dict[str, Any]:
        """Write ``text`` as ``<tool>.status`` and return the parsed record."""
        (self.log_dir / f"{tool}.status").write_text(text, encoding="utf-8")
        return cli._runner_status(self.log_dir, tool)

    # -- comments ---------------------------------------------------------------------

    def test_a_comment_carrying_an_equals_is_not_a_field(self) -> None:
        record = self.parse(
            "tool=trivy\n"
            "exit_code=0\n"
            "# note: the value is x=y, and this line is prose rather than a field\n"
            f"scan_root={STATUS_SCAN_ROOT}\n"
        )
        self.assertEqual(
            sorted(record["fields"]), ["exit_code", "scan_root", "tool"]
        )
        self.assertEqual(record["field_count"], 3)
        self.assertEqual(record["comment_lines"], 1)
        # A comment is a comment, not a rejected field: it is counted as one and is not a
        # defect in the file.
        self.assertEqual(record["unparsed_line_count"], 0)
        self.assertEqual(record["defects"], [])

    def test_a_comment_cannot_shadow_the_runners_own_exit_code(self) -> None:
        """The shadowing F13 names: a commented example overwriting authoritative state."""
        record = self.parse(
            "tool=trivy\n"
            "exit_code=0\n"
            f"scan_root={STATUS_SCAN_ROOT}\n"
            "# exit_code=137 -- what a killed run would have recorded\n"
        )
        self.assertEqual(record["fields"]["exit_code"], "0")
        self.assertEqual(record["exit_code"], 0)
        self.assertEqual(record["exit_status"], cli.EXIT_STATUS_EXITED)
        self.assertEqual(record["comment_lines"], 1)
        self.assertEqual(record["duplicate_field_count"], 0)

    def test_an_indented_comment_is_still_a_comment(self) -> None:
        record = self.parse("tool=trivy\n    # indented prose with an = in it\n")
        self.assertEqual(record["comment_lines"], 1)
        self.assertEqual(sorted(record["fields"]), ["tool"])

    # -- key syntax at column zero ------------------------------------------------------

    def test_an_indented_field_name_is_not_a_field(self) -> None:
        """The fenced-example hole: an indented ``exit_code=`` must not become the value."""
        record = self.parse("tool=trivy\nexit_code=0\n    exit_code=137\n")
        self.assertEqual(record["fields"]["exit_code"], "0")
        self.assertEqual(record["exit_code"], 0)
        self.assertEqual(record["unparsed_line_count"], 1)
        rejected = record["unparsed_lines"][0]
        self.assertEqual(rejected["line"], 3)
        self.assertEqual(rejected["reason"], cli.STATUS_LINE_INVALID_KEY)
        self.assertIn("exit_code=137", rejected["excerpt"])

    def test_every_shape_of_invalid_key_is_rejected_with_that_reason(self) -> None:
        for line in (
            "two words=value",
            "trailing-space =value",
            "hyphenated-key=value",
            "1leading_digit=value",
            "=value",
            "dotted.key=value",
            "$interpolated=value",
        ):
            with self.subTest(line=line):
                record = self.parse(f"tool=trivy\n{line}\n")
                self.assertEqual(sorted(record["fields"]), ["tool"])
                self.assertEqual(record["unparsed_line_count"], 1)
                self.assertEqual(
                    record["unparsed_lines"][0]["reason"],
                    cli.STATUS_LINE_INVALID_KEY,
                )

    def test_a_plain_field_name_at_column_zero_is_accepted(self) -> None:
        record = self.parse(
            "tool=trivy\n_leading_underscore=1\nWithCaps9=2\nartifact_bytes=1024\n"
        )
        self.assertEqual(
            sorted(record["fields"]),
            ["WithCaps9", "_leading_underscore", "artifact_bytes", "tool"],
        )
        self.assertEqual(record["artifact_bytes_literal"], "1024")
        self.assertEqual(record["unparsed_line_count"], 0)

    def test_a_line_with_no_separator_is_recorded_with_its_own_reason(self) -> None:
        record = self.parse("tool=trivy\nthis line is prose and carries no separator\n")
        self.assertEqual(record["unparsed_line_count"], 1)
        self.assertEqual(
            record["unparsed_lines"][0]["reason"], cli.STATUS_LINE_NO_SEPARATOR
        )

    # -- duplicates ---------------------------------------------------------------------

    def test_a_duplicate_key_keeps_the_first_occurrence(self) -> None:
        record = self.parse(
            "tool=trivy\nexit_code=0\nelapsed_seconds=12\nexit_code=137\n"
        )
        self.assertEqual(record["fields"]["exit_code"], "0")
        self.assertEqual(record["exit_code"], 0)
        self.assertEqual(record["elapsed_seconds"], 12)

    def test_a_duplicate_is_recorded_rather_than_dropped_silently(self) -> None:
        record = self.parse(
            "tool=trivy\nexit_code=0\nelapsed_seconds=12\nexit_code=137\n"
        )
        self.assertEqual(record["duplicate_field_count"], 1)
        duplicate = record["duplicate_fields"][0]
        self.assertEqual(duplicate["key"], "exit_code")
        self.assertEqual(duplicate["value"], "137")
        self.assertEqual(duplicate["line"], 4)
        self.assertEqual(duplicate["first_seen_on_line"], 2)
        self.assertIn("first", duplicate["kept"])
        # The duplicate is named as a defect in the file, with its count and the key.
        classes = {entry["class"]: entry for entry in record["defects"]}
        self.assertIn(cli.STATUS_DEFECT_DUPLICATE_KEY, classes)
        self.assertEqual(classes[cli.STATUS_DEFECT_DUPLICATE_KEY]["count"], 1)
        self.assertEqual(
            classes[cli.STATUS_DEFECT_DUPLICATE_KEY]["keys"], ["exit_code"]
        )

    def test_several_duplicates_are_each_recorded(self) -> None:
        record = self.parse(
            "tool=trivy\nexit_code=0\ntool=semgrep\nexit_code=1\nscan_root=/a\n"
        )
        self.assertEqual(record["fields"]["tool"], "trivy")
        self.assertEqual(record["fields"]["exit_code"], "0")
        self.assertEqual(record["duplicate_field_count"], 2)
        self.assertEqual(
            sorted(entry["key"] for entry in record["duplicate_fields"]),
            ["exit_code", "tool"],
        )

    # -- blanks, excerpts and the closed vocabulary ------------------------------------

    def test_blank_lines_are_counted_and_are_not_defects(self) -> None:
        record = self.parse("tool=trivy\n\n   \nexit_code=0\n")
        self.assertEqual(record["blank_lines"], 2)
        self.assertEqual(record["field_count"], 2)
        self.assertEqual(record["defects"], [])

    def test_a_long_rejected_line_is_excerpted_and_says_so(self) -> None:
        limit = cli._STATUS_LINE_EXCERPT_LIMIT
        line = "x" * (limit + 50)
        record = self.parse(f"tool=trivy\n{line}\n")
        excerpt = record["unparsed_lines"][0]["excerpt"]
        self.assertTrue(excerpt.startswith("x" * limit))
        self.assertIn(f"cut at {limit}", excerpt)
        self.assertLess(len(excerpt) - len(f"... [cut at {limit}]"), len(line))

    def test_the_defect_vocabulary_is_closed_and_every_entry_carries_a_count(self) -> None:
        record = self.parse(
            "tool=trivy\nexit_code=0\nexit_code=1\n    exit_code=2\nprose with no sep\n"
        )
        self.assertEqual(
            sorted(entry["class"] for entry in record["defects"]),
            sorted([cli.STATUS_DEFECT_DUPLICATE_KEY, cli.STATUS_DEFECT_UNPARSABLE_LINE]),
        )
        for entry in record["defects"]:
            with self.subTest(defect=entry["class"]):
                self.assertIsInstance(entry["count"], int)
                self.assertGreater(entry["count"], 0)
                self.assertTrue(entry["handling"])
        self.assertEqual(record["unparsed_line_count"], 2)
        self.assertEqual(record["duplicate_field_count"], 1)

    def test_the_record_publishes_the_contract_it_applied(self) -> None:
        record = self.parse("tool=trivy\n")
        self.assertIn(cli._STATUS_KEY_PATTERN, record["parser_contract"])
        self.assertIn("first occurrence", record["parser_contract"])

    # -- the fields the rest of the pipeline reads --------------------------------------

    def test_the_projected_fields_come_from_the_first_occurrence_only(self) -> None:
        record = self.parse(
            "tool=trivy\n"
            "exit_code=0\n"
            "elapsed_seconds=7\n"
            f"scan_root={STATUS_SCAN_ROOT}\n"
            "scan_root_source=SPARK_SRC\n"
            "# scan_root=/tmp/blitzy-harness-scratch/0/smoke\n"
            "scan_root=/tmp/elsewhere\n"
        )
        self.assertEqual(record["scan_root"], STATUS_SCAN_ROOT)
        self.assertEqual(record["scan_root_source"], "SPARK_SRC")
        self.assertEqual(record["exit_code"], 0)
        self.assertEqual(record["elapsed_seconds"], 7)

    def test_a_negative_exit_code_is_read_as_a_number(self) -> None:
        record = self.parse("tool=trivy\nexit_code=-1\n")
        self.assertEqual(record["exit_code"], -1)
        self.assertEqual(record["exit_status"], cli.EXIT_STATUS_EXITED)

    def test_a_status_file_with_no_readable_exit_code_is_a_timeout(self) -> None:
        record = self.parse("tool=trivy\nelapsed_seconds=9\n")
        self.assertIsNone(record["exit_code"])
        self.assertEqual(record["exit_status"], cli.EXIT_STATUS_TIMEOUT)

    def test_an_exit_code_that_is_only_prose_does_not_become_a_number(self) -> None:
        record = self.parse("tool=trivy\nexit_code=killed by the supervisor\n")
        self.assertIsNone(record["exit_code"])
        self.assertEqual(record["exit_code_literal"], "killed by the supervisor")
        self.assertEqual(record["exit_status"], cli.EXIT_STATUS_TIMEOUT)

    def test_an_absent_status_file_is_unrecorded_rather_than_empty(self) -> None:
        record = cli._runner_status(self.log_dir, "no-such-tool")
        self.assertFalse(record["present"])
        self.assertEqual(record["fields"], {})
        self.assertEqual(record["exit_status"], cli.EXIT_STATUS_UNRECORDED)

    def test_no_log_tree_at_all_is_unrecorded_and_names_no_path(self) -> None:
        record = cli._runner_status(None, "trivy")
        self.assertIsNone(record["path"])
        self.assertFalse(record["present"])
        self.assertEqual(record["exit_status"], cli.EXIT_STATUS_UNRECORDED)


class CommittedStatusFileTest(unittest.TestCase):
    """Assert the parser against the nine status files this run's runners actually wrote.

    A regression rather than a unit test: the composed status files in this tree are the
    shapes that produced F13, and the two properties asserted here are the ones a future
    edit to the parser would break.  The tree is git-ignored and regenerated by the
    orchestrator, so its absence is a skip.
    """

    def setUp(self) -> None:
        if not COMMITTED_LOG_DIR.is_dir():
            self.skipTest(f"{COMMITTED_LOG_DIR} is absent (git-ignored, regenerated)")
        self.tools = [
            tool
            for tool in cli.ARTIFACT_ORDER
            if (COMMITTED_LOG_DIR / f"{tool}.status").is_file()
        ]
        if not self.tools:
            self.skipTest("no committed .status file to read")

    def test_every_field_name_is_a_plain_field_name(self) -> None:
        for tool in self.tools:
            record = cli._runner_status(COMMITTED_LOG_DIR, tool)
            with self.subTest(tool=tool):
                self.assertGreater(record["field_count"], 0)
                for key in record["fields"]:
                    self.assertRegex(key, FIELD_NAME_RE)
                    self.assertNotIn("#", key)

    def test_every_field_is_backed_by_a_line_that_begins_with_it(self) -> None:
        """No field may exist that only a comment or an indented example could produce."""
        for tool in self.tools:
            text = (COMMITTED_LOG_DIR / f"{tool}.status").read_text(
                encoding="utf-8", errors="replace"
            )
            lines = text.splitlines()
            record = cli._runner_status(COMMITTED_LOG_DIR, tool)
            for key, value in record["fields"].items():
                with self.subTest(tool=tool, key=key):
                    self.assertIn(f"{key}={value}", lines)

    def test_the_permissive_split_invents_fields_this_parser_refuses(self) -> None:
        """Every key the old rule would have produced and this one does not, is explained.

        The surplus is not asserted to be non-empty -- a regenerated tree may carry no
        composed commentary at all -- but every surplus key must be explained by the
        contract rather than merely absent: it is not a plain field name at column zero, or
        every line that would have produced it is a comment.
        """
        for tool in self.tools:
            text = (COMMITTED_LOG_DIR / f"{tool}.status").read_text(
                encoding="utf-8", errors="replace"
            )
            record = cli._runner_status(COMMITTED_LOG_DIR, tool)
            permissive: dict[str, list[str]] = {}
            for line in text.splitlines():
                key, separator, _value = line.partition("=")
                if separator:
                    permissive.setdefault(key, []).append(line)
            for key, sources in permissive.items():
                if key in record["fields"]:
                    continue
                with self.subTest(tool=tool, key=key):
                    self.assertTrue(
                        not FIELD_NAME_RE.match(key)
                        or all(line.strip().startswith("#") for line in sources)
                        or any(
                            entry["key"] == key for entry in record["duplicate_fields"]
                        ),
                        f"{tool}.status: {key!r} was dropped for no stated reason",
                    )


