        observed = cli.INGESTION_BOUNDS["observed_maxima"]
        self.assertEqual(observed["runner_metadata_depth"], depth)
        self.assertEqual(observed["runner_metadata_nodes"], nodes)
        self.assertEqual(observed["runner_metadata_string_characters"], longest)
        self.assertEqual(
            observed["runner_metadata_bytes"], committed.stat().st_size
        )
        self.assertIsNone(paths._metadata_shape_violation(document))


