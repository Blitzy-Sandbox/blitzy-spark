    def test_the_committed_metadata_is_inside_every_bound(self) -> None:
        """Measured here, independently, rather than taken from the published maxima."""
        committed = COMMITTED_LOG_DIR / cli.RUNNER_METADATA_FILENAME
        if not committed.is_file():
            self.skipTest(f"{committed} is absent; the log tree is git-ignored")
        document = json.loads(committed.read_text(encoding="utf-8"))
        depth = 0
        nodes = 0
        longest = 0
        stack: list[tuple[Any, int]] = [(document, 1)]
        while stack:
            value, level = stack.pop()
            nodes += 1
            depth = max(depth, level)
            if isinstance(value, Mapping):
                for name, member in value.items():
                    longest = max(longest, len(name))
                    stack.append((member, level + 1))
