class _OutputTargetTestCase(unittest.TestCase):
    """A repository, a log tree, a raw tree and an environment, all inside a temp dir.

    The tree is the shape ``harness/env.sh`` exports: the log and raw trees sit *inside* the
    repository root, which is what makes an output legitimately able to collide with an
    input and therefore what makes the distinctness checks worth asserting.
    """

    def setUp(self) -> None:
        self._directory = tempfile.TemporaryDirectory(prefix="blitzy-cli-outputs-")
        self.addCleanup(self._directory.cleanup)
        self.tmp = Path(self._directory.name)
        self.repo = self.tmp / "repo"
        self.log_dir = self.repo / "harness" / "artifacts" / "logs"
        self.raw_dir = self.repo / "harness" / "artifacts" / "raw"
        self.scope_dir = self.repo / "harness" / "scope"
        self.results_dir = self.repo / "oss-scan-results"
        self.spark_src = self.tmp / "spark-src"
        for directory in (
            self.log_dir,
            self.raw_dir,
            self.scope_dir,
            self.results_dir,
            self.spark_src,
        ):
            directory.mkdir(parents=True, exist_ok=True)
        self.allowlist = self.scope_dir / "allowlist.txt"
        self.allowlist.write_text("core/src/main/**\n", encoding="utf-8")
        self.runner_metadata = self.log_dir / cli.RUNNER_METADATA_FILENAME
        self.runner_metadata.write_text("{}\n", encoding="utf-8")

    @property
    def env(self) -> dict[str, str]:
        """The environment ``harness/env.sh`` would have exported for this tree."""
        return {
            "HARNESS_REPO_ROOT": str(self.repo),
            "HARNESS_LOG_DIR": str(self.log_dir),
            "HARNESS_RAW_DIR": str(self.raw_dir),
            "HARNESS_SCOPE_FILE": str(self.allowlist),
            "SPARK_SRC": str(self.spark_src),
        }

    def resolve(
        self, *argv: str, environment: Mapping[str, str] | None = None
    ) -> cli.Inputs:
        """Resolve inputs the way ``main`` does, with an environment of our own."""
        namespace = cli.build_parser().parse_args(list(argv))
        return cli.resolve_inputs(
            namespace, self.env if environment is None else environment
        )

    def refusal(
        self, *argv: str, environment: Mapping[str, str] | None = None
    ) -> cli.ConfigurationFault:
        """Assert the invocation is refused, and return the fault for inspection."""
        with self.assertRaises(cli.ConfigurationFault) as caught:
            self.resolve(*argv, environment=environment)
        fault = caught.exception
        self.assertEqual(fault.exit_code, cli.EXIT_CONFIG)
        return fault


class OutputContainmentTest(_OutputTargetTestCase):
    """Each output resolves inside the one root that owns it, or the run stops."""

    def test_the_default_invocation_is_accepted_and_records_what_it_checked(self) -> None:
        inputs = self.resolve()
        self.assertEqual(
            inputs.findings_json, self.repo / cli.FINDINGS_JSON_RELATIVE
        )
        self.assertEqual(inputs.findings_csv, self.repo / cli.FINDINGS_CSV_RELATIVE)
        self.assertEqual(inputs.run_record, self.log_dir / cli.RUN_RECORD_FILENAME)
        guards = inputs.output_guards
        self.assertEqual(guards["repository_root"], str(self.repo))
        self.assertEqual(guards["repository_root_source"], "$HARNESS_REPO_ROOT")
        self.assertEqual(guards["log_tree"], str(self.log_dir))
        self.assertEqual(
            guards["owners"],
            {
                "--findings-json": str(self.repo),
                "--findings-csv": str(self.repo),
                "--run-record": str(self.log_dir),
            },
        )
        self.assertEqual(len(guards["checks_passed"]), 4)
        self.assertGreater(guards["input_identities_compared_against"], 0)

    def test_a_dataset_file_outside_the_repository_root_is_refused(self) -> None:
        for flag in ("--findings-json", "--findings-csv"):
            with self.subTest(flag=flag):
                stray = self.tmp / "elsewhere.out"
                fault = self.refusal(flag, str(stray))
                self.assertEqual(fault.reason, cli.HALT_OUTPUT_OUTSIDE_OWNER)
                self.assertEqual(fault.details["output"], flag)
                self.assertEqual(fault.details["path"], str(stray))
                self.assertEqual(fault.details["owner_root"], str(self.repo))
                self.assertIn("$HARNESS_REPO_ROOT", fault.details["owner_root_source"])
                self.assertIn(str(stray), fault.message)

    def test_a_dataset_file_reached_with_dot_dot_is_refused(self) -> None:
        escape = str(self.results_dir / ".." / ".." / "escaped.json")
        fault = self.refusal("--findings-json", escape)
        self.assertEqual(fault.reason, cli.HALT_OUTPUT_OUTSIDE_OWNER)

    def test_the_run_record_outside_the_log_tree_is_refused(self) -> None:
        stray = self.results_dir / cli.RUN_RECORD_FILENAME
        fault = self.refusal("--run-record", str(stray))
        self.assertEqual(fault.reason, cli.HALT_OUTPUT_OUTSIDE_OWNER)
        self.assertEqual(fault.details["output"], "--run-record")
        self.assertEqual(fault.details["owner_root"], str(self.log_dir))
        self.assertIn("$HARNESS_LOG_DIR", fault.details["owner_root_source"])

