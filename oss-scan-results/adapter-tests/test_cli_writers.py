"""Assert what the normalizer will and will not write, and what it refuses to read as a field.

What this module tests
---------------------
Three properties of ``harness/lib/normalize/cli.py`` that nothing else in this tree
exercises, because nothing else in this tree constructs :class:`normalize.cli.Inputs` or
calls :func:`normalize.cli.main`:

1.  **Where an output may land.**  The three files this module writes -- ``findings.json``,
    ``findings.csv`` and ``normalize-run.json`` -- each have exactly one owner root, must be
    three different files, may not name any input, and may not be reached through a symbolic
    link at or below their owner.  A configured path that satisfies none of those is a
    fault in the invocation, so every one of these is a :class:`cli.ConfigurationFault`
    (exit ``78``) raised before anything is read or written (CWE-73, CWE-59).
2.  **That required evidence fails closed.**  ``normalize-run.json`` is the only account of
    how the dataset was produced (AAP 0.6.1, AAP 0.9.1).  A run whose record could not be
    written, read back and parsed does not report success -- the loss becomes the outcome
    (CWE-703).  And the record's location comes from ``--run-record`` or
    ``$HARNESS_LOG_DIR`` and from nowhere else: there is no working-directory fallback, so a
    run started in the wrong directory cannot write its audit evidence somewhere no reader
    and no manifest will ever look.
3.  **What counts as a field in a ``.status`` file.**  ``harness/lib/scope.sh`` writes a
    key=value block, and the composed record around it carries commented headers, fenced
    command examples and indented prose -- any of which can contain an ``=``.  Splitting
    every line on its first ``=`` invents fields out of documentation, and assigning
    unconditionally lets the last of several duplicates win; between them, a comment can
    shadow authoritative state such as ``exit_code`` or ``scan_root``.  The parser is
    asserted directly, line by line, including on the nine committed status files.

Why these are asserted here rather than through the pipeline
-----------------------------------------------------------
Every check above happens before the first artifact is opened, or after the last row is
written, so a pipeline-level test would establish them only incidentally and only for the
one configuration the committed artifacts happen to describe.  The subject is the *rule*:
an output aimed at the raw tree must be refused whether or not that tree holds artifacts,
and a lost run record must sink a run whose data was otherwise perfect.  So the pipeline is
stubbed where its result is not the subject -- :func:`cli._execute` in the two ``main``
tests -- and the guard being tested is always the real one.

Hermetic by construction
------------------------
Every test builds its own repository inside a :class:`tempfile.TemporaryDirectory`: a log
tree, a raw tree, an allowlist, a ``runner-metadata.json`` and an ``oss-scan-results``
directory, with an environment mapping supplied as an argument rather than read from the
process.  The two tests that must exercise ``main`` -- which reads ``os.environ`` itself --
save the environment, the working directory and every patched attribute, and restore all
three in a ``finally``.  Nothing is written outside a temporary directory; in particular
this module never writes ``oss-scan-results/findings.json``, ``findings.csv`` or anything
under ``harness/artifacts/``.  The nine committed ``.status`` files are read and never
written, and the test that reads them skips where the tree is absent, since that tree is
git-ignored and regenerated by the orchestrator.

Prohibitions this module observes
---------------------------------
It judges no finding and performs no cross-tool interpretation (AAP 0.3.2): the status
files are parsed, never compared with each other.  It carries no secret value in any
literal, message or docstring, this tree being committed to git.  It edits nothing under
``harness/lib/normalize/``: a defect there is reported, not repaired here.

Rules
-----
No user-specified rules govern this file: ``review_rules`` reports "No user rules
provided.", which AAP 0.7 and AAP 0.10.2 corroborate.  Enterprise-standard best practice
applies in their place, which is why each refusal is asserted on its *reason* and on the
component or collision its message names, rather than only on the fact that something was
raised.

Running it
----------
Standard library only, no ``pytest``, and runnable from any working directory::

    python3 -m unittest discover -s oss-scan-results/adapter-tests -p 'test_cli_writers.py'
"""

