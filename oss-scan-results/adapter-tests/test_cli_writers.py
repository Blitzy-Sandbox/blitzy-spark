class _ArtifactIngestionTestCase(unittest.TestCase):
    """A temporary raw tree, an outcome to mutate, and the refusal assertions, shared.

    Carries no test of its own.  Two classes drive
    :func:`cli._ingest_artifact_document` -- :class:`ArtifactIngestionTest` on the
    read-validate-parse-measure sequence as a whole, and
    :class:`PreParseStructuralGateTest` on the ORDER of it -- and one copy of these four
    helpers is what keeps them asserting against the same outcome shape.
    """

    def setUp(self) -> None:
        self._directory = tempfile.TemporaryDirectory(prefix="blitzy-ingest-")
        self.addCleanup(self._directory.cleanup)
        self.raw_dir = Path(self._directory.name)

    def outcome(self, tool: str = "gitleaks") -> cli.ArtifactOutcome:
        return cli.ArtifactOutcome(
            tool=tool,
            scanner_class="secret",
            artifact_filename=f"{tool}.json",
            present=True,
            parse_status=cli.PARSE_STATUS_CLEAN,
            artifact={"path": str(self.raw_dir / f"{tool}.json"), "present": True},
        )

    def write(self, body: str | bytes, *, tool: str = "gitleaks") -> Path:
        path = self.raw_dir / f"{tool}.json"
        if isinstance(body, bytes):
            path.write_bytes(body)
        else:
            path.write_text(body, encoding="utf-8")
        return path

    def refusal(
        self, path: Path, *, tool: str = "gitleaks"
    ) -> tuple[cli.NormalizeHalt, cli.ArtifactOutcome]:
        outcome = self.outcome(tool)
        with self.assertRaises(cli.NormalizeHalt) as caught:
            cli._ingest_artifact_document(tool, path, outcome=outcome)
        self.assertEqual(outcome.parse_status, cli.PARSE_STATUS_FAILED)
        self.assertTrue(outcome.artifact["ingestion"]["refused"])
        self.assertEqual(
            outcome.artifact["ingestion"]["refused_reason"], caught.exception.reason
        )
        # The halt is durable, so it must survive serialisation into the run record.
        json.dumps(caught.exception.as_dict())
        return caught.exception, outcome


class ArtifactIngestionTest(_ArtifactIngestionTestCase):
    """Every hostile artifact becomes a NAMED halt with the measurement in its details.

    The subject is :func:`cli._ingest_artifact_document`, which owns the whole of the
    read-validate-parse-measure sequence for an artifact.  The outcome it mutates is the one
    that is already in the run record when it is called, so each test asserts the record's
    side of the refusal as well as the exception's.
    """

    # -- the accepted case ------------------------------------------------------------

    def test_a_valid_artifact_is_returned_with_its_measurements_recorded(self) -> None:
        path = self.write('[{"RuleID": "generic-api-key", "File": "a.py"}]')
        outcome = self.outcome()
        document = cli._ingest_artifact_document("gitleaks", path, outcome=outcome)

        self.assertEqual(document[0]["RuleID"], "generic-api-key")
        ingestion = outcome.artifact["ingestion"]
        self.assertFalse(ingestion["refused"])
        self.assertTrue(ingestion["measured_before_routing"])
        self.assertEqual(ingestion["observed_bytes"], path.stat().st_size)
        self.assertEqual(ingestion["bytes_read"], path.stat().st_size)
        self.assertEqual(ingestion["depth"], 3)
        self.assertEqual(ingestion["nodes"], 4)
        self.assertEqual(ingestion["longest_string"], len("generic-api-key"))
        self.assertEqual(ingestion["bounds"]["artifact_bytes"], cli.ARTIFACT_BYTE_LIMIT)
        self.assertEqual(ingestion["bounds"]["json_depth"], cli.JSON_DEPTH_LIMIT)
        self.assertEqual(outcome.parse_status, cli.PARSE_STATUS_CLEAN)
        json.dumps(outcome.as_dict())

    def test_the_document_is_measured_before_it_is_routed_to_a_shape(self) -> None:
        """White-box on the order, which is the property the bound depends on."""
        source = inspect.getsource(cli._process_present_artifact)
        self.assertLess(
            source.index("_ingest_artifact_document("),
            source.index("shape.route_artifact("),
            msg="an artifact must be bounded before any adapter or router sees it",
        )

    # -- the byte cap -----------------------------------------------------------------

    def test_an_over_sized_artifact_is_refused_before_a_byte_is_read(self) -> None:
        path = self.write("[" + ", ".join(["0"] * 200) + "]")
        reads: list[Path] = []
        real_reader = cli._read_bounded_artifact_text

        def recording_reader(target: Path, limit: int) -> tuple[str, int, bool]:
            reads.append(target)
            return real_reader(target, limit)

        previous = cli.ARTIFACT_BYTE_LIMIT
        cli.ARTIFACT_BYTE_LIMIT = 32
        cli._read_bounded_artifact_text = recording_reader  # type: ignore[assignment]
        try:
            halt, _ = self.refusal(path)
        finally:
            cli.ARTIFACT_BYTE_LIMIT = previous
            cli._read_bounded_artifact_text = real_reader  # type: ignore[assignment]

        self.assertEqual(halt.reason, cli.HALT_ARTIFACT_TOO_LARGE)
        self.assertEqual(halt.exit_code, cli.EXIT_HALT)
        self.assertEqual(halt.details["observed_bytes"], path.stat().st_size)
        self.assertEqual(halt.details["byte_cap"], 32)
        self.assertEqual(
            reads,
            [],
            msg="os.stat decides the byte cap; a read that happened first would be the "
            "allocation the cap exists to prevent",
        )

    def test_an_artifact_that_grew_since_the_stat_is_refused_on_read(self) -> None:
        """The check-then-read gap, closed by reading cap + 1 rather than cap bytes."""
        path = self.write("[" + ", ".join(["0"] * 200) + "]")
        real_stat = os.stat

        def small_stat(target: Any, *args: Any, **kwargs: Any) -> Any:
            result = real_stat(target, *args, **kwargs)
            if str(target) == str(path):
                # Report a size inside the cap for the file being ingested only.
                return os.stat_result(
                    (result.st_mode, result.st_ino, result.st_dev, result.st_nlink,
                     result.st_uid, result.st_gid, 8,
                     int(result.st_atime), int(result.st_mtime), int(result.st_ctime))
                )
            return result

        previous = cli.ARTIFACT_BYTE_LIMIT
        cli.ARTIFACT_BYTE_LIMIT = 32
        os.stat = small_stat  # type: ignore[assignment]
        try:
            halt, _ = self.refusal(path)
        finally:
            os.stat = real_stat  # type: ignore[assignment]
            cli.ARTIFACT_BYTE_LIMIT = previous

        self.assertEqual(halt.reason, cli.HALT_ARTIFACT_TOO_LARGE)
        self.assertEqual(halt.details["measured_bytes_before_read"], 8)
        self.assertEqual(halt.details["observed_bytes"], 33)
        self.assertIn("grew between the two", halt.message)

    # -- decoding and parsing ---------------------------------------------------------

    def test_bytes_that_are_not_utf8_are_named_rather_than_replaced(self) -> None:
        path = self.write(b'[{"RuleID": "\xff\xfe"}]')
        halt, _ = self.refusal(path)
        self.assertEqual(halt.reason, cli.HALT_ARTIFACT_NOT_UTF8)
        self.assertIsInstance(halt.details["byte_offset"], int)
        self.assertIn("decoded strictly", halt.message)

    def test_invalid_json_is_still_the_invalid_json_halt(self) -> None:
        """The bounds are additions; the pre-existing classification is unchanged."""
        path = self.write("{not json")
        halt, _ = self.refusal(path)
        self.assertEqual(halt.reason, cli.HALT_ARTIFACT_INVALID_JSON)
        self.assertEqual(halt.details["line"], 1)

    def test_a_document_nested_past_the_recursion_limit_becomes_a_named_halt(
        self,
    ) -> None:
        """json's C scanner recurses per level, so this raises inside json.loads.

        20,000 is measured rather than chosen: on this interpreter (CPython 3.13, reported
        recursion limit 1,000) a 5,000-level document still parses and is refused by the
        depth cap instead, and 20,000 raises ``RecursionError: maximum recursion depth
        exceeded while decoding a JSON array``.

        The depth cap is now enforced on the document's TEXT before ``json.loads`` is
        called, so at the production cap of 64 this document never reaches the parser at
        all -- which is the point of the fix, and is asserted by
        :class:`PreParseStructuralGateTest`'s
        ``test_a_document_nested_past_the_recursion_limit_never_reaches_the_parser``.
        The arm this test names still exists as defence in depth against the gate being
        wrong, so the cap is lifted above the document's depth to reach it: the gate accepts
        20,000 levels, ``json``'s scanner does not, and the conversion is exercised exactly
        as before.
        """
        depth = 20_000
        lift_cap(self, cli, "JSON_DEPTH_LIMIT", depth + 5_000)
        path = self.write("[" * depth + "]" * depth)
        halt, _ = self.refusal(path)
        self.assertEqual(halt.reason, cli.HALT_ARTIFACT_EXHAUSTED_STACK)
        self.assertEqual(halt.details["stage"], "parse")
        self.assertEqual(halt.details["depth_cap"], cli.JSON_DEPTH_LIMIT)
        self.assertEqual(halt.details["recursion_limit"], sys.getrecursionlimit())

    def test_an_integer_literal_cpython_refuses_becomes_its_own_named_halt(self) -> None:
        """Valid JSON, and an ``int()`` above the 4,300-digit conversion limit.

        The digit bound is now enforced on the literal before ``json.loads`` reaches
        ``int()``, so at the production cap of 64 this document is refused without being
        parsed -- :class:`PreParseStructuralGateTest`'s
        ``test_an_over_long_numeric_literal_is_refused_before_the_conversion`` asserts
        that.  The cap is lifted here so the ``ValueError`` arm behind the gate is
        still exercised, and the halt it produces is the same named one it always was.
        """
        lift_cap(self, cli, "STATUS_NUMERIC_DIGIT_LIMIT", 6_000)
        path = self.write('{"n": ' + "9" * 5_000 + "}")
        halt, _ = self.refusal(path)
        self.assertEqual(halt.reason, cli.HALT_ARTIFACT_LITERAL_UNCONVERTIBLE)
        self.assertEqual(halt.details["error_type"], "ValueError")

    def test_a_document_over_the_depth_cap_is_refused_with_its_bound(self) -> None:
        depth = cli.JSON_DEPTH_LIMIT + 6
        path = self.write("[" * depth + "]" * depth)
